function renderizarCards(lista) {
    if (!grid) return;
    if (lista.length === 0) {
        grid.innerHTML = `<p class="col-span-full text-center py-10 text-gray-500">Nenhum resultado encontrado.</p>`;
        return;
    }

    grid.innerHTML = lista.map(p => `
        <div class="bg-white rounded-2xl shadow-lg overflow-hidden border border-gray-100 flex flex-col h-full transition-all hover:shadow-2xl">
            <div class="relative bg-gray-200">
                <img src="${p.imagem}" alt="${p.nome}" class="w-full h-64 object-cover">
                <div class="absolute top-2 right-2 bg-green-600 text-white text-[10px] px-2 py-1 rounded-full font-bold uppercase shadow-md">
                    ${p.cultura}
                </div>
            </div>
            <div class="p-5 flex flex-col flex-grow">
                <h2 class="text-xl font-bold text-gray-800">${p.nome}</h2>
                <p class="text-sm italic text-gray-400 mb-4">${p.cientifico}</p>
                
                <div class="mb-4 flex-grow">
                    <h3 class="font-bold text-gray-700 text-sm">👁️ Sintomas no Campo:</h3>
                    <p class="text-gray-600 text-sm leading-relaxed">${p.sintomas}</p>
                </div>
                
                <div class="bg-green-50 p-4 rounded-xl border-l-4 border-green-500 mt-auto">
                    <h3 class="text-xs font-black text-green-800 uppercase mb-1">🌿 Manejo Biológico:</h3>
                    <p class="text-green-900 text-xs">${p.controle}</p>
                </div>
            </div>
        </div>
    `).join('');
}

function filtrar() {
    const termo = searchInput.value.toLowerCase();
    const cultura = filterCultura.value;
    const filtrados = pragas.filter(p => {
        const matchTermo = p.nome.toLowerCase().includes(termo) || 
                           p.sintomas.toLowerCase().includes(termo) ||
                           p.tags.some(t => t.includes(termo));
        const matchCultura = cultura === 'todas' || p.cultura === cultura;
        return matchTermo && matchCultura;
    });
    renderizarCards(filtrados);
}

searchInput.addEventListener('input', filtrar);
filterCultura.addEventListener('change', filtrar);

window.onload = () => renderizarCards(pragas);

